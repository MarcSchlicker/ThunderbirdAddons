"use strict";
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const root=path.resolve(__dirname,'..');
const files=[...new Set(cp.execFileSync('git',['ls-files','--cached','--others','--exclude-standard','-z'],{cwd:root}).toString().split('\0').filter(Boolean))];
const rules=[
 ['private-key',/-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/],
 ['token',/\b(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{40,}|AKIA[A-Z0-9]{16})\b/],
 ['credential-url',/https?:\/\/[^\s/@:]+:[^\s/@]+@/],
 ['user-path',/[A-Z]:[\\/]+Users[\\/]+(?!Public\b|<|\{|\$)[\w.-]+[\\/]/i],
 ['work-artifact',/HANDOFF_20[0-9]{2}|PRUEFNACHWEISE[_]|TB_CONNECT_STATUS[_]AND_BACKLOG|generated by (?:A[I]|Code[x])|KI[ .]generiert/i],
];
const forbidden=/(?:^|\/)(?:AGENTS\.md|CLAUDE\.md|PROJECT_(?:STATUS|KNOWLEDGE|ARCHIVE)\.md|local\.properties|\.env(?:\..*)?|[^/]+\.(?:apk|aab|xpi|keystore|jks|sqlite|log))$|(?:^|\/)(?:\.codex|\.agents)(?:\/|$)/i;
let findings=[];
for(const f of files){
 const p=path.join(root,f);if(!fs.existsSync(p)||!fs.statSync(p).isFile())continue;
 if(forbidden.test(f))findings.push({file:f,rule:'private-file'});
 const b=fs.readFileSync(p);if(b.includes(0))continue;
 b.toString('utf8').split(/\r?\n/).forEach((line,i)=>{for(const [rule,re] of rules){
 // Upstream URL-parser fixture tests user-info parsing; it is not a live credential.
 const fixture=rule==='credential-url'&&f.endsWith('/message/html/HttpUriParserTest.kt')&&line.trim()==='assertValidUri("'+['http', '://', 'test', ':secret@google.com/")'].join('');
 const invalidDavFixture=rule==='credential-url'&&f.endsWith('/Dav4jvmCalDavClientTest.kt')&&line.trim()==='"'+['https', '://', 'user', ':pass@cloud.example.invalid/",'].join('');
 if(!fixture&&!invalidDavFixture&&re.test(line))findings.push({file:f,line:i+1,rule});
 }});
}
console.log(JSON.stringify({files:files.length,findings},null,2));
process.exitCode=findings.length?1:0;
